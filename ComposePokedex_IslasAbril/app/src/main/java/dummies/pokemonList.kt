fun showAllPokemons(): List<Pokemon> {
    return pokemonList
}
fun returnOnePokemon(): Pokemon{
    return pokemonList.random()
}

fun getPokemonByID(id: Int): Pokemon{
    return pokemonList.first{
        it.number == id
    }
}

fun getPreviousPokemon(number:Int):Pokemon{
    val index= pokemonList.indexOf(pokemonList.filter{
        pokemon -> pokemon.number == number
    }.get(0))
    val previousIndex = if (index == 0) pokemonList.size-1 else index - 1
    return pokemonList[previousIndex]
}
fun getNextPokemon(number:Int):Pokemon{
    val index= pokemonList.indexOf(pokemonList.filter{
            pokemon -> pokemon.number == number
    }.get(0))
    val nextIndex = if (index >= pokemonList.size - 1) 0 else index + 1
    return pokemonList[nextIndex]
}
